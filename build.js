// Builds the standalone, single-file game at ./index.html from ./src.
// Usage: node build.js
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, 'src');
const shell = fs.readFileSync(path.join(SRC, '00-shell.html'), 'utf8');
const scripts = fs.readdirSync(SRC).filter(f => f.endsWith('.js')).sort()
  .map(f => '/* ===== ' + f + ' ===== */\n' + fs.readFileSync(path.join(SRC, f), 'utf8'))
  .join('\n');

// Ability animation frames present under assets/heroes/anim (<key>_<slot>_<n>.png), so the page only requests files that exist
const animDir = path.join(__dirname, 'assets', 'heroes', 'anim'), ANIM = {};
if (fs.existsSync(animDir)) fs.readdirSync(animDir).forEach(f => { const m = /^([a-z]+)_([QWER])_(\d)\.png$/.exec(f); if (!m) return; const k = ANIM[m[1]] || (ANIM[m[1]] = {}); k[m[2]] = Math.max(k[m[2]] || 0, +m[3]); });
const tanDir = path.join(__dirname, 'assets', 'heroes', 'tan', 'anim'), ANIM_TAN = {};
if (fs.existsSync(tanDir)) fs.readdirSync(tanDir).forEach(f => { if (/^[a-z]+_[QWER]_\d\.png$/.test(f)) ANIM_TAN[f.slice(0, -4)] = 1; });
const animJs = '/* ===== generated by build.js ===== */\nvar ANIM_FRAMES = ' + JSON.stringify(ANIM) + ', ANIM_TAN = ' + JSON.stringify(ANIM_TAN) + ';\n';
const cut = shell.indexOf('</style>') + '</style>'.length;
const head = shell.slice(0, cut);
const body = shell.slice(cut).trim();

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="description" content="Plastic Front: an all-ARAM toy-soldier MOBA fought across a backyard sandbox.">
<style>*,*::before,*::after{box-sizing:border-box}html,body{margin:0;padding:0}[hidden]{display:none!important}</style>
${head}
</head>
<body>
${body}
<script>
(function () {
'use strict';
${animJs}${scripts}
})();
</script>
</body>
</html>
`;

fs.writeFileSync(path.join(__dirname, 'index.html'), html);
console.log('Built index.html (' + Math.round(html.length / 1024) + ' KB)');

// The shared simulation as an ES module for the Cloudflare Worker: one closure, with live getters for every top-level name
// (the same shape server/sim.js builds at runtime for Node).
const simBody = ['10-data.js', '20-sim-core.js', '30-sim-update.js'].map(f => fs.readFileSync(path.join(SRC, f), 'utf8')).join('\n');
const names = new Set();
for (const m of simBody.matchAll(/^function\s+([A-Za-z_$][\w$]*)/gm)) names.add(m[1]);
for (const m of simBody.matchAll(/^var\s+([A-Za-z_$][\w$]*)/gm)) names.add(m[1]);
const api = [...names].map(n => `get ${n}() { return ${n}; }, set ${n}(v) { ${n} = v; }`).join(',\n');
fs.mkdirSync(path.join(__dirname, 'worker'), { recursive: true });
fs.writeFileSync(path.join(__dirname, 'worker', 'sim.gen.js'), '// generated by build.js from src/10, 20, 30; do not edit\nexport function createSim() {\n"use strict";\n' + simBody + '\nreturn {\n' + api + '\n};\n}\n');

// dist/: the static site the Worker serves (index.html plus the art), for `wrangler deploy`
const dist = path.join(__dirname, 'dist');
fs.rmSync(dist, { recursive: true, force: true });
fs.mkdirSync(dist, { recursive: true });
fs.writeFileSync(path.join(dist, 'index.html'), html);
fs.cpSync(path.join(__dirname, 'assets'), path.join(dist, 'assets'), { recursive: true });
console.log('Built worker/sim.gen.js and dist/');
